export const DEFAULT_COUNTRY = COUNTRIES[0]; // India

export const getCountryFlag = (code) => {
  if (!code) return '🌐';
  if (code.toUpperCase() === 'GLOBAL' || code.toUpperCase() === 'ALL') return '🌐';
  const found = COUNTRIES.find(c => c.code.toUpperCase() === code.toUpperCase());
  if (found && found.flag) return found.flag;
  if (code.length === 2) {
    try {
      const codePoints = code
        .toUpperCase()
        .split('')
        .map(char => 127397 + char.charCodeAt(0));
      return String.fromCodePoint(...codePoints);
    } catch (e) {
      return '🌍';
    }
  }
  return '🌍';
};

export const getCountryByCode = (code, fallbackName = '') => {
  if (!code) return DEFAULT_COUNTRY;
  const found = COUNTRIES.find(c => c.code.toUpperCase() === code.toUpperCase());
  if (found) return found;
  return {
    code: code.toUpperCase(),
    name: fallbackName || code.toUpperCase(),
    flag: getCountryFlag(code),
    popularCities: []
  };
};

export const getPopularCitiesForCountry = (countryCode) => {
  const c = getCountryByCode(countryCode);
  return c?.popularCities || DEFAULT_COUNTRY.popularCities;
};
